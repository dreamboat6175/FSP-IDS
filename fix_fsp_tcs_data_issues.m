fprintf(fid, ['function [is_valid, issues] = checkDataQuality(results)\n'...
'%%CHECKDATAQUALITY 检查数据质量\n'...
'%% 识别可能导致FSP-TCS:MissingData警告的问题\n'...
'\n'...
'is_valid = true;\n'...
'issues = {};\n'...
'\n'...
'%% 检查基本结构\n'...
'required_fields = {''attacker'', ''defenders'', ''performance''};\n'...
'for i = 1:length(required_fields)\n'...
'    if ~isfield(results, required_fields{i})\n'...
'        is_valid = false;\n'...
'        issues{end+1} = sprintf(''缺少字段: %s'', required_fields{i});\n'...
'    end\n'...
'end\n'...
'\n'...
'%% 检查攻击者数据\n'...
'if isfield(results, ''attacker'') && isfield(results.attacker, ''performance'')\n'...
'    perf = results.attacker.performance;\n'...
'    attacker_fields = {''success_history'', ''reward_history'', ''target_distribution''};\n'...
'    for i = 1:length(attacker_fields)\n'...
'        if ~isfield(perf, attacker_fields{i}) || isempty(perf.(attacker_fields{i}))\n'...
'            is_valid = false;\n'...
'            issues{end+1} = sprintf(''攻击者数据缺失: %s'', attacker_fields{i});\n'...
