'    algorithms = fieldnames(results.defenders);\n'...
'    for i = 1:length(algorithms)\n'...
'        alg = algorithms{i};\n'...
'        if isfield(results.defenders.(alg), ''performance'')\n'...
'            perf = results.defenders.(alg).performance;\n'...
'            defender_fields = {''detection_rate'', ''success_rate'', ''avg_reward''};\n'...
'            for j = 1:length(defender_fields)\n'...
'                if ~isfield(perf, defender_fields{j}) || isempty(perf.(defender_fields{j}))\n'...
'                    is_valid = false;\n'...
'                    issues{end+1} = sprintf(''%s防御者数据缺失: %s'', alg, defender_fields{j});\n'...
