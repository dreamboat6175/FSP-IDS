function fix_fsp_tcs_data_issues()
%FIX_FSP_TCS_DATA_ISSUES 修复FSP-TCS系统数据缺失和图表生成问题
%
% 此脚本解决以下问题：
% 1. FSP-TCS:MissingData 警告
% 2. 极坐标图生成失败：不支持将极坐标图添加到 axes
% 3. 数据字段缺失问题
% 4. 虚假数据生成问题

fprintf('🚀 开始修复FSP-TCS数据缺失和图表生成问题...\n\n');

try
    %% 第1步：备份原始文件
    fprintf('1️⃣ 备份原始文件...\n');
    backup_critical_files();
    
    %% 第2步：修复可视化报告生成器
    fprintf('2️⃣ 修复可视化报告生成器...\n');
    fix_visualization_report_issues();
    
    %% 第3步：修复极坐标图问题
    fprintf('3️⃣ 修复极坐标图生成问题...\n');
    fix_polar_chart_issues();
    
    %% 第4步：创建数据验证和默认值处理
    fprintf('4️⃣ 创建数据验证和默认值处理...\n');
    create_data_validation_system();
    
    %% 第5步：清理和验证
    fprintf('5️⃣ 清理临时文件并验证修复...\n');
    cleanup_and_verify();
    
    fprintf('\n🎉 FSP-TCS问题修复完成！\n');
    fprintf('💡 建议运行测试验证修复效果\n');
    
catch ME
    fprintf('❌ 修复过程出错: %s\n', ME.message);
    fprintf('📍 错误位置: %s (第%d行)\n', ME.stack(1).file, ME.stack(1).line);
    rethrow(ME);
end

end

function backup_critical_files()
%备份关键文件
files_to_backup = {
    'visualization/generateVisualizationReport.m',
    'visualization/EnhancedVisualization.m',
    'core/updatePerformanceMonitor.m'
};

timestamp = datestr(now, 'yyyymmdd_HHMMSS');
backup_dir = sprintf('backup_fix_%s', timestamp);

if ~exist(backup_dir, 'dir')
    mkdir(backup_dir);
end

for i = 1:length(files_to_backup)
    file_path = files_to_backup{i};
    if exist(file_path, 'file')
        [~, name, ext] = fileparts(file_path);
        backup_path = fullfile(backup_dir, [name '_backup' ext]);
        copyfile(file_path, backup_path);
        fprintf('   ✅ 已备份: %s\n', file_path);
    else
        fprintf('   ⚠️ 文件不存在: %s\n', file_path);
    end
end
end

